"""Re-score earlier real benchmark runs with the current methodology: python -m benchmark.reanalyze

Reads the raw per-item results in BENCHMARK_DIR/<run_id>/<system>.jsonl (no model calls), recomputes
strict exact accuracy, paired tests and the claim verdict, and writes RESULTS_DIR/reanalysis.md/.json.
Mock runs are skipped. Runs over the same dataset are also pooled; pooled numbers are repeated
measurements of the same questions (they capture run-to-run model variance, not new items).
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

from app.core.config import Settings
from benchmark.analysis import analyzer_validation
from benchmark.dataset import DATASETS_DIR, BenchmarkItem, load_dataset
from benchmark.evaluators import deterministic_check, is_checkable
from benchmark.report import VERDICT_LABEL, fmt, pct, table, write_report
from benchmark.run import assemble, summarize_system
from benchmark.runners import SYSTEM_BY_NAME, SYSTEMS, ItemResult

LABELS = {s.name: s.label for s in SYSTEMS}


def load_run(run_dir: Path, datasets: dict[str, dict[str, BenchmarkItem]]) -> tuple[str, dict[str, list[ItemResult]]] | None:
    results: dict[str, list[ItemResult]] = {}
    for path in sorted(run_dir.glob("*.jsonl")):
        if path.stem in SYSTEM_BY_NAME:
            with path.open(encoding="utf-8") as f:
                results[path.stem] = [ItemResult.model_validate_json(line) for line in f if line.strip()]
    if not results or any(r.record.mock_mode for rs in results.values() for r in rs):
        return None
    ids = {r.item_id for rs in results.values() for r in rs}
    dataset = next((name for name, items in datasets.items() if ids <= items.keys()), None)
    if dataset is None:
        return None
    items = datasets[dataset]
    # --exec-code is not recorded in old raw files; it was on iff any code item got a verdict.
    exec_code = any(r.deterministic_correct is not None and items[r.item_id].answer_type == "code" for rs in results.values() for r in rs)
    for rs in results.values():
        for r in rs:
            item = items[r.item_id]
            r.checkable = is_checkable(item, exec_code=exec_code)
            if item.answer_type == "numeric":  # re-score with the current (exact-integer) checker; code results are kept
                r.deterministic_correct = deterministic_check(item, r.record.answer, exec_code=False)
                r.attempt_correct = [deterministic_check(item, a.answer, exec_code=False) if a.answer is not None else None
                                     for a in r.record.attempts]
    return dataset, results


def lineup(results: dict[str, list[ItemResult]]) -> tuple[tuple[str, str], ...]:
    """The (tier, model) pairs that actually answered. Runs are pooled only within one lineup."""
    return tuple(sorted({(a.tier, a.model) for rs in results.values() for r in rs for a in r.record.attempts}))


def summarize_run(results: dict[str, list[ItemResult]], judge_cost: dict[str, float]) -> dict:
    systems = {name: summarize_system(SYSTEM_BY_NAME[name], rs, judge_cost) for name, rs in results.items()}
    return {"systems": systems, **assemble(systems, results)}


def pooled(runs: list[dict[str, list[ItemResult]]]) -> dict[str, list[ItemResult]]:
    """Concatenate runs that ran the same systems; item ids get a run prefix so pairing stays within a run."""
    common = set.intersection(*(set(r) for r in runs))
    out: dict[str, list[ItemResult]] = defaultdict(list)
    for n, run in enumerate(runs):
        for name in common:
            for r in run[name]:
                copy = r.model_copy(deep=True)
                copy.item_id = f"run{n}:{r.item_id}"
                copy.record.query_id = f"run{n}:{r.record.query_id}"
                out[name].append(copy)
    return dict(out)


def render(report: dict) -> str:
    out = ["# Re-analysis of recorded real-model runs\n",
           "Generated by `python -m benchmark.reanalyze` from raw per-item results (no new model calls). "
           "Primary metric: strict exact accuracy (unparseable answers count as wrong). Mock runs are excluded.\n"]
    for block in report["blocks"]:
        s = block["summary"]
        out.append(f"## {block['title']}\n")
        claim = s["claim"]
        out.append(f"**Verdict: {VERDICT_LABEL.get(claim['verdict'], claim['verdict'])}.** {claim['explanation']}\n")
        rows = []
        for name, v in s["systems"].items():
            st, c = v["strict"], s["comparisons"].get(name, {})
            ci = st["ci95"]
            rows.append([LABELS.get(name, name), f"{st['correct']}/{st['checked']}", pct(st["accuracy"]),
                         f"{pct(ci[0])}-{pct(ci[1])}" if ci else "n/a", str(st["unparseable"]), fmt(v["cost"]["mean"], 2),
                         fmt(v["cost_incl_judge"]["mean"], 2),
                         f"{c['cost_incl_judge_vs_cheap_x']:.2f}x" if c.get("cost_incl_judge_vs_cheap_x") is not None else "n/a",
                         fmt(v["serving_calls_mean"], 2), fmt(v["latency_ms"]["median"], 0), pct(v["escalation"]["rate"]),
                         "{total} ({necessary}/{unnecessary}/{unknown})".format(**v["escalations"])])
        out.append(table(["System", "Correct", "Strict acc.", "95% CI", "Unparseable", "Gen cost", "Cost incl. judge", "vs cheap",
                          "Calls/query", "p50 ms", "Escalation", "Escalations (nec/unnec/unknown)"], rows) + "\n")
        prow = [[k, str(p["items"]), str(p["wins"]), str(p["losses"]), fmt(p["sign_test_p"], 3)] for k, p in s["paired"].items()]
        if prow:
            out.append(table(["Paired comparison", "Items", "Wins", "Losses", "Sign-test p"], prow) + "\n")
    return "\n".join(out)


def main() -> int:
    settings = Settings()
    judge_cost = {role: p["normalized_cost"] for role, p in json.loads(settings.models_config.read_text(encoding="utf-8")).items() if isinstance(p, dict)}
    datasets = {p.stem: {i.id: i for i in load_dataset(p)} for p in sorted(DATASETS_DIR.glob("*.jsonl"))}
    by_dataset: dict[str, list[tuple[str, dict]]] = defaultdict(list)
    for run_dir in sorted(p for p in settings.benchmark_dir.iterdir() if p.is_dir()):
        loaded = load_run(run_dir, datasets)
        if loaded:
            by_dataset[loaded[0]].append((run_dir.name, loaded[1]))
    if not by_dataset:
        print(f"No real (non-mock) runs with per-system results under {settings.benchmark_dir}.", file=sys.stderr)
        return 1
    blocks = []
    for dataset, runs in sorted(by_dataset.items()):
        for run_id, results in runs:
            blocks.append({"title": f"`{dataset}` run {run_id} ({len(next(iter(results.values())))} items)",
                           "summary": summarize_run(results, judge_cost)})
        groups: dict[tuple, list[dict]] = defaultdict(list)
        for _, r in runs:
            if {"smart_router", "always_weak", "always_strong"} <= r.keys():
                groups[lineup(r)].append(r)
        for models, full in groups.items():
            if len(full) > 1:
                names = ", ".join(f"{t}=`{m}`" for t, m in models)
                blocks.append({"title": f"`{dataset}` pooled over {len(full)} complete runs with one model lineup ({names}); "
                                        "repeated measurements of the same items",
                               "summary": summarize_run(pooled(full), judge_cost)})
    report = {"blocks": [{"title": b["title"], "summary": {k: v for k, v in b["summary"].items() if k != "systems"} | {
        "systems": {n: {k: v for k, v in s.items() if k != "items"} for n, s in b["summary"]["systems"].items()}}} for b in blocks]}
    settings.results_dir.mkdir(parents=True, exist_ok=True)
    (settings.results_dir / "reanalysis.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (settings.results_dir / "reanalysis.md").write_text(render(report), encoding="utf-8")
    print(f"Wrote {settings.results_dir / 'reanalysis.md'} ({len(blocks)} blocks)")
    refresh_latest(settings, by_dataset, judge_cost)
    return 0


def refresh_latest(settings: Settings, by_dataset: dict[str, list[tuple[str, dict]]], judge_cost: dict[str, float]) -> None:
    """Re-score the run that latest.json describes, so the dashboard and latest.md use the current methodology."""
    path = settings.results_dir / "latest.json"
    if not path.exists():
        return
    latest = json.loads(path.read_text(encoding="utf-8"))
    match = next(((d, r) for d, runs in by_dataset.items() for run_id, r in runs if run_id == latest.get("run_id")), None)
    if match is None:
        return
    dataset, results = match
    systems = {name: summarize_system(SYSTEM_BY_NAME[name], rs, judge_cost) for name, rs in results.items()}
    items = list(load_dataset(DATASETS_DIR / f"{dataset}.jsonl"))
    cfg = latest["config"]
    latest.update({"systems": systems, **assemble(systems, results), "rescored_by": "benchmark.reanalyze",
                   "analyzer": analyzer_validation(items, cfg["routing_thresholds"]["cheap_max"], cfg["routing_thresholds"]["mid_max"])})
    path.write_text(json.dumps(latest, indent=2), encoding="utf-8")
    write_report(latest, settings.results_dir / "latest.md")
    print(f"Re-scored {path} (run {latest['run_id']}) and latest.md")


if __name__ == "__main__":
    sys.exit(main())
